export function useMedicalAnalysis() {
  const analyze = useCallback((transcript: string, language: Language): AnalysisResult => {
    const lowerTranscript = transcript.toLowerCase().trim();
    console.info('[MedicalAnalysis] Input:', { transcript, language, lowerTranscript });

    // ── Score-based matching: find the BEST match, not the first ──
    let bestMatch: SymptomEntry | null = null;
    let bestScore = 0;
    let bestKeyword = '';

    for (const entry of symptomDatabase) {
      let score = 0;
      let longestKeyword = '';

      for (const keyword of entry.keywords) {
        const lowerKeyword = keyword.toLowerCase();
        // Skip very short keywords (≤2 chars) to prevent false substring matches
        if (lowerKeyword.length <= 2) continue;

        if (lowerTranscript.includes(lowerKeyword)) {
          // Weight by keyword length — longer/more specific keywords score higher
          score += lowerKeyword.length;
          if (lowerKeyword.length > longestKeyword.length) {
            longestKeyword = keyword;
          }
        }
      }

      if (score > bestScore) {
        bestScore = score;
        bestMatch = entry;
        bestKeyword = longestKeyword;
      }
    }

    if (bestMatch && bestScore > 0) {
      console.info('[MedicalAnalysis] Best match:', {
        id: bestMatch.id,
        score: bestScore,
        matchedVia: bestKeyword,
      });
      return {
        status: bestMatch.status,
        response: bestMatch.advice[language],
        isEmergency: bestMatch.isEmergency,
      };
    }

    console.info('[MedicalAnalysis] No symptomDB match, checking fallback keywords…');

    // 2. Fallback: check generic emergency keywords
    const allEmergency = Object.values(emergencyKeywords).flat();
    const hasEmergency = allEmergency.some(keyword =>
      lowerTranscript.includes(keyword.toLowerCase())
    );
    if (hasEmergency) {
      console.info('[MedicalAnalysis] Matched emergency keyword');
      return {
        status: 'emergency',
        response: genericResponses.emergency[language],
        isEmergency: true,
      };
    }

    // 3. Fallback: check generic monitor keywords
    const allMonitor = Object.values(monitorKeywords).flat();
    const needsMonitor = allMonitor.some(keyword =>
      lowerTranscript.includes(keyword.toLowerCase())
    );
    if (needsMonitor) {
      console.info('[MedicalAnalysis] Matched monitor keyword');
      return {
        status: 'monitor',
        response: genericResponses.monitor[language],
        isEmergency: false,
      };
    }

    // 4. Check if it's clearly NON-health (blacklist approach)
    const isNonHealth = nonHealthKeywords.some(keyword =>
      lowerTranscript.includes(keyword.toLowerCase())
    );
    if (isNonHealth) {
      const matchesAnyHealth = romanizedHealthWords.some(keyword =>
        lowerTranscript.includes(keyword.toLowerCase())
      );
      if (!matchesAnyHealth) {
        console.info('[MedicalAnalysis] Out of scope');
        return {
          status: 'safe',
          response: genericResponses.outOfScope[language],
          isEmergency: false,
        };
      }
    }

    // 5. Default: treat as health-related with helpful generic advice
    console.info('[MedicalAnalysis] Default safe response');
    return {
      status: 'safe',
      response: genericResponses.safe[language],
      isEmergency: false,
    };
  }, []);

  const getGreeting = useCallback((language: Language): string => {
    return genericResponses.greeting[language];
  }, []);

  const getNoInputResponse = useCallback((language: Language): string => {
    return genericResponses.noInput[language];
  }, []);

  const getOutOfScopeResponse = useCallback((language: Language): string => {
    return genericResponses.outOfScope[language];
  }, []);

  return { analyze, getGreeting, getNoInputResponse, getOutOfScopeResponse };
}
